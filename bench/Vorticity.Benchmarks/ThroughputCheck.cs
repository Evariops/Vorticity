// ns/value, the axis that gives ABSOLUTES instead of a ranking.
//
// bench/BASELINE.md's per-encoding table says of itself: "this is a ranking, not a measurement".
// The reason is arithmetic. Its files are 4096 rows, and ~35 us of every row in it is the fixed
// open-and-walk cost both implementations pay before a single value is decoded. `fastlanes.bitpacked`
// reads 40.9 us against Rust's 35.4 -- five microseconds of decode under thirty-five of overhead --
// which is why that row moved from 1.26x to 1.18x while its kernel got 3.6x faster. Every ratio in
// that table is pulled toward 1.0 by a constant neither side can avoid, and the smaller the real
// difference the harder it is pulled.
//
// One million rows per file changes the arithmetic rather than the estimator: the fixed cost is
// unchanged, so its SHARE falls by roughly the row ratio, and what is left is the decoder.
//
// THE INPUTS ARE NOT IN THE REPOSITORY, and Corpus.cs already drew that line for real datasets:
// "those are gigabytes that do not belong in a repository". These are 330 MB for 50 encodings.
// Generate them once, into the cache directory this looks in by default:
//
//   bench/gen-throughput.sh
//   dotnet run -c Release --project bench/Vorticity.Benchmarks -- --throughput --check
//
// `VORTICITY_THROUGHPUT_CORPUS` still overrides the location for a corpus kept elsewhere.
//
// THE MANIFEST IS WHY `--check` CAN MEAN ANYTHING. The fifty numbers in `References` are ratchets
// against a set of bytes that lives outside the repository and is regenerated by hand. Which bytes
// was recorded nowhere: not the row count, not the Vortex release, not the generator's commit, not
// a hash. The generator has already changed what these files contain once -- `fastlanes.delta` and
// `vortex.zstd_buffers` were silently absent (`2575a6f`) -- and a reference measured on one corpus
// and checked against another is wrong with nothing to say so. So `--check` now REFUSES a corpus
// with no `manifest.json`, refuses one generated at a row count other than the references', and
// verifies the sha256 of every file it is about to measure.
//
// They carry NO SIDECAR and nothing asserts a value from them: correctness is the 4096-row corpus's
// job, and these exist only to push the fixed cost below the noise floor. The manifest says which
// bytes a ratchet was measured against; it says nothing about what is in them.
