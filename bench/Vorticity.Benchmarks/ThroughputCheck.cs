    /// <summary>
    /// The reference binary the three tables above were calibrated against, or null when none was
    /// recorded. <see cref="RustReader.Fingerprint"/> names the one a run actually loaded.
    /// </summary>
    /// <remarks>
    /// Writing a fingerprint here without recalibrating all three tables under that binary would be
    /// the exact claim this field exists to check, made falsely. `--recalibrate` prints the line to
    /// paste here beside the table it prints, so the two are recorded together or not at all; and
    /// under a binary other than this one, `--rebase` lets a reference rise, the denominator having
    /// changed. Record it once the three tables are recalibrated: after it, a fourth recalibration
    /// under the same binary is an ordinary one again.
    ///
    /// Once it holds a value, `--check` refuses to gate against a different binary rather than
    /// report differences it cannot attribute.
    /// </remarks>
    private static readonly string? CalibratedShim = "1be9345d4816";

    /// <summary>Measures every generated file and reports ns/value for both readers.</summary>
    /// <param name="check">Whether to hold each ratio to its ceiling and exit non-zero when over.</param>
    /// <returns>0 on success, 1 when an encoding is over its ceiling, 2 when the inputs are absent.</returns>
    internal static async Task<int> RunAsync(bool check, string[] only) =>
        await RunAsync(check, only, 0, false, false).ConfigureAwait(false);

    /// <summary>Measures every generated file and reports ns/value for both readers.</summary>
    /// <param name="check">Whether to hold each ratio to its ceiling and exit non-zero when over.</param>
    /// <param name="only">Family name substrings; empty measures everything.</param>
    /// <param name="recalibrate">
    /// When positive, measure that many passes and print a replacement <see cref="References"/>
    /// table instead of gating -- the same command `RatioCheck` has, for the same reason: lowering
    /// fifty ratchets by hand is how they stop being lowered.
    /// </param>
    /// <param name="rebase">
    /// Let a reference RISE, and only where the estimator changed: a grouped round (k > 1), or a
    /// reference binary other than <see cref="CalibratedShim"/>. See `RatioCheck`.
    /// </param>
    /// <param name="hold">
    /// Print every reference back unchanged and refresh only the dispersion, for a run that is
    /// measuring how steady each encoding is rather than deciding where its ratchet belongs.
    /// </param>
    /// <param name="rebaseFrom">
    /// With <paramref name="recalibrate"/>, the reference binary the table was set under, to carry
    /// every reference over to the running one.
    /// </param>
    internal static async Task<int> RunAsync(
        bool check, string[] only, int recalibrate, bool rebase, bool hold, string? rebaseFrom = null)
    {
        string root = Root;

        // The files, not the directory: the generator creates the directory before it writes
        // anything, so one that failed or was interrupted leaves it behind empty, and that needs
        // the same command as no directory at all.
        string[] files = Directory.Exists(root)
            ? Directory.GetFiles(root, "*.vortex", SearchOption.AllDirectories)
            : [];
        if (files.Length == 0)
        {
            Console.Error.WriteLine(
                $"No throughput inputs at {root}.\n" +
                "They are generated, not committed -- 468 MB for 57 encodings. Produce them with:\n" +
                "  bench/gen-throughput.sh\n" +
                $"or point {Variable} at a directory that already holds them.");
            return 2;
        }

        bool rust = RustReader.Available;
        if (check && !rust)
        {
            Console.Error.WriteLine(
                $"--check needs the reference: vxbench not found ({RustReader.ExpectedPath}).\n" +
                "Build it with: cd tools/vxbench-rs && cargo build --release");
            return 2;
        }

        Array.Sort(files, StringComparer.Ordinal);
        if (only.Length > 0)
        {
            // Measuring one family takes half a minute where the whole axis takes five, which is
            // the difference between checking a kernel change and not bothering. The gate still
            // runs everything; this narrows the report.
            List<string> kept = [];
            foreach (string file in files)
            {
                string name = Path.GetFileNameWithoutExtension(file);
                foreach (string pattern in only)
                {
                    if (name.Contains(pattern, StringComparison.OrdinalIgnoreCase))
                    {
                        kept.Add(file);
                        break;
                    }
                }
            }

            files = [.. kept];
        }

        if (files.Length == 0)
        {
            Console.Error.WriteLine($"no input under {root} matches {string.Join(", ", only)}");
            return 2;
        }

        if (Page is not null && (only.Length > 0 || recalibrate > 0 || Axis == Workload.Scan || IsConfirming))
        {
            Console.Error.WriteLine(Axis == Workload.Scan
                ? "The page shows the scan as the report measures it; this run does not write it."
                : "The page takes a run of every file; it is not written by this run.");
            Page = null;
        }

        // THE NARROW FORM DOES NOT GATE. Measured on identical bytes: the same
        // file reads 6 452 us when the run holds three files and 8 557 us when it holds one --
        // +32 % on OUR side, with the reference flat at 5 071-5 235 either way. It is not the rank
        // in the run (three files behave like fifty-four) and not the process state after 49
        // decodes: it is dynamic PGO. `DOTNET_TieredCompilation=0` or `DOTNET_TieredPGO=0` closes
        // the gap to 0.4 % (7 029 against 7 056), so a run that measures one file is judging code
        // the runtime never finished optimizing.
        //
        // A systematic bias is worse than dispersion, because it looks like a result: `fsst` came
        // out at 1.68 against a 1.51 ceiling on a healthy repository. So the filter and `--check`
        // are refused together, and the message says which of the two to drop.
        if (check && only.Length > 0 && recalibrate == 0)
        {
            Console.Error.WriteLine(
                $"`--throughput {string.Join(" ", only)} --check` is refused: a run that measures " +
                "a few files judges code the JIT has not finished optimizing, which costs OUR " +
                "side up to 32% and the reference nothing. Either gate on the " +
                "whole axis:\n  --throughput --check\nor measure the family without gating:\n  " +
                $"--throughput {string.Join(" ", only)}");
            return 2;
        }

        Manifest? manifest = ReadManifest(root, out string manifestProblem);
        if (check && manifest is null)
        {
            Console.Error.WriteLine(
                $"{manifestProblem}\nThe references below are ratchets against a specific set of " +
                "bytes, and without a manifest there is nothing to say these are those bytes. " +
                "Regenerate with bench/gen-throughput.sh, or drop --check to measure without " +
                "gating.");
            return 2;
        }

        if (check && manifest is not null &&
            VerifyAgainstManifest(manifest, files, root) is string mismatch)
        {
            Console.Error.WriteLine(mismatch);
            return 2;
        }

        string what = Axis switch
        {
            Workload.Take => string.Create(
                CultureInfo.InvariantCulture, $"TAKE ({TakeCount} rows every {TakeStride})"),
            Workload.Write => "WRITE (read back out to a sink that keeps nothing)",
            _ => "THROUGHPUT",
        };
        Console.Out.WriteLine(
            $"{what}: median per-round ratio with a 95% bootstrap interval, {MinRounds}+ rounds after a " +
            $"{WarmupBudget.TotalSeconds.ToString("F0", CultureInfo.InvariantCulture)}s warm-up per file, " +
            $"from {root}");
        Console.Out.WriteLine(manifest is null
            ? $"  corpus: NO MANIFEST -- {manifestProblem}"
            // "rows/file" was read as a fact and believed by a scenario that then strode past the
            // end of a 50 000-row file. It is the gauge the generator aimed at; the `rows`
            // column says what each file really has, and the run names the exceptions at the end.
            : $"  corpus: {manifest.Rows} rows/file (gauge), vortex {manifest.Vortex}, generated by " +
              $"{Shorten(manifest.Generator?.Commit)}" +
              (manifest.Generator?.Dirty == true ? " (dirty tree)" : string.Empty));
        // The denominator, named. A ratio is only comparable to the reference it is held against
        // if both were measured through the same reference binary, and nothing used to say which.
        if (rust)
        {
            string running = RustReader.Fingerprint ?? "unknown";
            Console.Out.WriteLine(CalibratedShim is null
                ? $"  reference binary: {running}; these references record none, so a move in the " +
                  "denominator would read here as a move in the code"
                : string.Equals(running, CalibratedShim, StringComparison.Ordinal)
                    ? $"  reference binary: {running}, the one these references were calibrated against"
                    : $"  reference binary: {running}, but these references were calibrated against " +
                      $"{CalibratedShim}: the denominator is not the one they were set on");

            // Refusing rather than reporting: a ratio measured through a different reference binary
            // is not a smaller or larger version of the same number, it is a number about something
            // else, and every verdict built on it -- OVER, STALE, PINNED -- would be about the
            // rebuild. `--recalibrate 3` under the running binary is what settles it.
            if (check && recalibrate == 0 && CalibratedShim is not null
                      && !string.Equals(running, CalibratedShim, StringComparison.Ordinal))
            {
                Console.Error.WriteLine(
                    $"REFUSED: these references were calibrated against reference binary " +
                    $"{CalibratedShim} and this process loaded {running}. Recalibrate under the one " +
                    $"in the tree (`--throughput --recalibrate 3`) and record its fingerprint, or " +
                    $"restore the binary the references name.");
                return 2;
            }
        }

        if (check)
        {
            Console.Out.WriteLine(
                $"  held to reference x {Margin.ToString("F2", CultureInfo.InvariantCulture)}");
        }

        Console.Out.WriteLine(
            rust
                ? "  encoding                             rows      ours      rust  ns/value   rust ns/v  ratio  [   95% interval]   n   k     mde" +
                  (check ? " reference ceiling" : string.Empty)
                : "  encoding                             rows batches       ours   ns/value   (no vxbench: absolutes only)");

        List<string> failures = [];

        // Files on which the two sides returned different rows: never timed, and the run fails.
        List<string> disagreed = [];
        List<string> stale = [];
        List<string> blunt = [];
        Dictionary<string, List<double>> measured = [];
        Dictionary<string, bool> grouped = [];
        List<string> unreferenced = [];

        // Files whose real row count is not the manifest's gauge.
        List<string> offGauge = [];

        // The names behind `failures`, for the confirming run.
        List<string> over = [];

        // Every file both sides measured, and the ones the reference declines, for the page.
        List<(string Encoding, Measurement Measured)> shown = [];
        List<string> declined = [];

        // On the write axis, the bytes each writer produced per file: what its time bought.
        Dictionary<string, (long Ours, long Theirs)> written = [];

        // Axes whose interval never reaches their reference.
        List<string> pinned = [];
        // A PASS IS A PROCESS when recalibrating: measured over twenty runs of one
        // axis each, between-run variance is two to three times the within-run variance, and a 95%
        // within-run interval contains the grand median 11 or 12 times out of 20 rather than 19.
        // Passes inside one process share a JIT, a heap, a page cache and a thermal state, so a
        // reference built from them is narrower than what the gate has to survive.
        if (recalibrate > 1)
        {
            return await RecalibrateAcrossProcessesAsync(only, recalibrate, rebase, hold, rebaseFrom)
                .ConfigureAwait(false);
        }

        foreach (string file in files)
        {
            string name = Path.GetFileNameWithoutExtension(file);
            if (Axis == Workload.Write
                && Array.FindIndex(ReferenceCannotWrite, entry => entry.Encoding == name) is var cannot and >= 0)
            {
                Console.Out.WriteLine(
                    $"  {name,-32} skipped: the reference cannot write this encoding " +
                    $"({ReferenceCannotWrite[cannot].Reason})");
                declined.Add(name);
                continue;
            }

            long rows;
            try
            {
                rows = await OursAsync(file).ConfigureAwait(false);
            }
            catch (Exception e) when (Axis == Workload.Write)
            {
                // THE WRITE AXIS REPORTS ITS OWN FAILURES INSTEAD OF DYING ON THEM, and it found
                // four the first time it ran: `list`, `listview` and `map` throw a format
                // exception, and `parquet_variant` an InvalidOperationException from inside
                // `ArrayBlobWriter`. Every one of those files READS, so "unreadable" would have
                // been a lie; and letting the exception out aborts the other 46 encodings, which
                // is how one broken column hides a table.
                string detail = e.Message.Split('\n')[0];
                Console.Out.WriteLine($"  {name,-32} write failed: {e.GetType().Name}: {detail}");
                continue;
            }
            catch (Exception e) when (e is VortexUnsupportedException or VortexFormatException)
            {
                // An encoding this build cannot read is not a failure of this axis: the corpus
                // coverage test owns that question, and reporting it here would duplicate it badly.
                Console.Out.WriteLine($"  {name,-32} unreadable: {e.GetType().Name}");
                continue;
            }

            if (rows == 0)
            {
                continue;
            }

            // The header used to print the manifest's row count as a FACT about every file,
            // and at least one file is not at the gauge -- `table_wide` has 50 000 where the
            // manifest says 1 000 000. That lie is what `ScatteredTake` believed when it strode
            // past the end of a file and ended the process. Counting the exceptions here is
            // cheaper than trusting the gauge anywhere else.
            // Only the scan axis: `rows` is what OursAsync returned, and on take that is the number
            // of rows TAKEN (64), not the file's. Comparing it to the gauge called all fifty-seven
            // off-gauge on the first run of this check.
            if (Axis == Workload.Scan && manifest is not null && manifest.Rows > 0 &&
                rows != manifest.Rows)
            {
                offGauge.Add(string.Create(
                    CultureInfo.InvariantCulture, $"  {name}: {rows} rows, not {manifest.Rows}"));
            }

            // BOTH SIDES MUST ANSWER WITH THE SAME ROWS BEFORE EITHER IS TIMED. `--ffi-check` holds
            // seven corpus files to that; these fifty-seven were timed on faith, and a reference
            // that failed on one returned a negative count in a few microseconds, which the scan
            // axis would have timed as a decode.
            if (rust && Theirs(file) is var answered && answered != rows)
            {
                string line = string.Create(CultureInfo.InvariantCulture,
                    $"  {name,-32} different rows: {rows} on our side, {answered} on the reference's");
                Console.Out.WriteLine(line);
                disagreed.Add(line);
                continue;
            }

            // A writer can be fast by compressing less: the page prints each side's bytes beside
            // its time. Untimed, one write a side.
            if (rust && Axis == Workload.Write && Page is not null)
            {
                written[name] = (
                    await Vorticity.Bench.Scenarios.ScenarioSet.WrittenBytes(file).ConfigureAwait(false),
                    RustReader.Require(RustReader.WriteBytes(file), "written bytes"));
            }

            // A take emits one batch per selected split; the count is the scan's story, not its.
            long batches = Axis == Workload.Scan
                ? await CountBatches(file).ConfigureAwait(false)
                : 0;
            Measurement m;
            try
            {
                m = await MeasureAsync(file, rust).ConfigureAwait(false);
            }
            catch (InvalidOperationException e) when (recalibrate > 0 && Axis == Workload.Write)
            {
                // A calibration pass outlives a reference that cannot write a file, which is how a
                // carry meets the build it leaves behind. The gate skips only what
                // ReferenceCannotWrite declares.
                Console.Out.WriteLine($"  {name,-32} skipped in this pass: {e.Message}");
                continue;
            }

            if (recalibrate > 0)
            {
                if (!measured.TryGetValue(name, out List<double>? seen))
                {
                    seen = [];
                    measured[name] = seen;
                }

                seen.Add(m.Ratio.Median);
                grouped[name] = m.Repeats > 1;
                continue;
            }

            double ours = m.Ours;
            double theirs = m.Theirs;
            double nsPerValue = ours * 1000.0 / rows;

            if (rust && theirs > 0)
            {
                double rustNs = theirs * 1000.0 / rows;
                Interval ratio = m.Ratio;
                string suffix = string.Empty;
                if (check)
                {
                    Reference? entry = ReferenceFor(name);
                    if (entry is null)
                    {
                        unreferenced.Add(string.Create(
                            CultureInfo.InvariantCulture,
                            $"        (\"{name}\", {Ref(ratio.Median)}),"));
                        suffix = "        --      --   NO REF";
                    }
                    else
                    {
                        Reference reference = entry.Value;

                        // The widest of the flat margin, what this encoding's own passes showed and
                        // the drift it shows between runs. A five-microsecond axis and a
                        // fifty-millisecond one do not resolve the same change, and a ceiling that
                        // pretends they do reports a regression nobody caused on the short one.
                        double drift = DriftOf(name);
                        double band = Math.Max(Margin - 1, Math.Max(reference.Spread, drift));
                        double ceiling = reference.Ratio * (1 + band);
                        suffix = string.Create(
                            CultureInfo.InvariantCulture,
                            $" {Ref(reference.Ratio),9} {Ref(ceiling),7}");

                        // THE LOWER BOUND DECIDES: a median over the ceiling with
                        // an interval straddling it is a coin toss, and failing on it is what made
                        // two of four invocations red with nothing changed.
                        if (ratio.Low > ceiling)
                        {
                            suffix += "   OVER";
                            failures.Add(string.Create(
                                CultureInfo.InvariantCulture,
                                $"  {name}: {Ref(ratio.Median)} {ratio} entirely over the {Ref(ceiling)} ceiling."));
                            over.Add(name);
                        }
                        else if (ratio.High < reference.Ratio * StaleBelow)
                        {
                            suffix += "   STALE";
                            stale.Add(string.Create(
                                CultureInfo.InvariantCulture,
                                $"  {name}: {Ref(ratio.Median)} against a {Ref(reference.Ratio)} reference -- lower it."));
                        }
                        else if (ratio.Median > ceiling)
                        {
                            suffix += "   noisy";
                            blunt.Add(string.Create(
                                CultureInfo.InvariantCulture,
                                $"  {name}: {Ref(ratio.Median)} is over {Ref(ceiling)} but {ratio} straddles it."));
                        }
                        else if (ratio.Low > reference.Ratio * (1 + reference.Spread))
                        {
                            // PINNED is STALE's mirror. STALE says an axis has too much headroom;
                            // PINNED says it has none, because even the best reading of the run
                            // does not reach the reference. The axis then lives entirely inside the
                            // margin and passes only on that, which is not the same as passing.
                            //
                            // Measured against the reference WIDENED BY ITS OWN DISPERSION, not
                            // against the bare figure: an encoding whose passes fall eight per cent
                            // apart will sit above a reference set at the best of them about as
                            // often as not, and calling that unreachable makes the report noise
                            // rather than a finding. What stays pinned after this is an encoding
                            // the axis genuinely cannot reach.
                            suffix += "   PINNED";
                            pinned.Add(string.Create(
                                CultureInfo.InvariantCulture,
                                $"  {name}: {ratio} never reaches its {Ref(reference.Ratio)} reference " +
                                $"-- unreachable, not a target."));
                        }
                    }
                }

                Console.Out.WriteLine(string.Create(
                    CultureInfo.InvariantCulture,
                    $"  {name,-32} {rows,10} {ours,9:F0}us {theirs,9:F0}us {nsPerValue,9:F2} {rustNs,10:F2} " +
                    $"{Ref(ratio.Median),6} {ratio} {ratio.Samples,3} {m.Repeats,3} {ratio.MinimumDetectableEffect,6:P1}{suffix}"));
                shown.Add((name, m));
            }
            else
            {
                Console.Out.WriteLine(string.Create(
                    CultureInfo.InvariantCulture,
                    $"  {name,-32} {rows,10} {batches,7} {ours,9:F0}us {nsPerValue,10:F2}"));
            }
        }

        if (recalibrate > 0)
        {
            // One pass: print the machine-readable lines the parent process collects.
            foreach ((string name, List<double> seen) in measured)
            {
                Console.Out.WriteLine(string.Create(
                    CultureInfo.InvariantCulture,
                    $"{PassPrefix}{name}\t{seen[0]:R}\t{(grouped.GetValueOrDefault(name) ? 1 : 0)}"));
            }

            return 0;
        }

        if (!rust)
        {
            Console.Out.WriteLine(
                $"\nvxbench not found ({RustReader.ExpectedPath}); the ours column is an absolute " +
                "and there is no ratio. Build it with: cd tools/vxbench-rs && cargo build --release");
        }

        if (offGauge.Count > 0)
        {
            Console.Out.WriteLine(
                $"\n{offGauge.Count} file(s) are not at the manifest's {manifest?.Rows} rows. The " +
                "header states the gauge, not a fact about every file; a scenario that strides " +
                "through a file must read its row count:");
            offGauge.ForEach(Console.Out.WriteLine);
        }

        if (unreferenced.Count > 0)
        {
            Console.Out.WriteLine(
                // It used to name References whatever the axis was, so the fifty-five lines a
                // write run printed invited pasting write ratios into the SCAN table.
                $"\n{unreferenced.Count} encoding(s) have no reference. Add these lines to " +
                $"ThroughputCheck.{TableName}, having checked the machine is quiet:");
            foreach (string line in unreferenced)
            {
                Console.Out.WriteLine(line);
            }
        }

        if (blunt.Count > 0)
        {
            Console.Out.WriteLine(
                $"\n{blunt.Count} encoding(s) are over the ceiling on the median but not on the " +
                "interval -- re-run; if one stays over, it is real:");
            blunt.ForEach(Console.Out.WriteLine);
        }

        foreach (string line in stale)
        {
            Console.Out.WriteLine(line);
        }

        if (pinned.Count > 0)
        {
            Console.Out.WriteLine(
                $"\n{pinned.Count} reference(s) the axis never reaches. `--recalibrate` cannot fix " +
                "these: it refuses to loosen, so it reprints the old value and says HELD " +
                "forever. Raising one is a deliberate, dated, justified edit:");
            pinned.ForEach(Console.Out.WriteLine);
        }

        if (check && Axis == Workload.Scan)
        {
            string held = string.Join(", ", ReadDrift.Select(d => string.Create(
                CultureInfo.InvariantCulture, $"{d.Encoding} +{d.Spread:P0}")));
            Console.Out.WriteLine(
                $"\n{ReadDrift.Length} encoding(s) are held to their drift between runs " +
                "instead of the flat margin, so a regression smaller than that drift passes " +
                $"on them: {held}");
        }

        foreach (string failure in failures)
        {
            Console.Error.WriteLine(failure);
        }

        // A ratio between two different answers is not a ratio, and a page with one of them missing
        // reads as a page measured whole.
        if (disagreed.Count > 0)
        {
            disagreed.ForEach(Console.Error.WriteLine);
            Console.Error.WriteLine($"{disagreed.Count} file(s) answered differently by the two sides; nothing written.");
            return 1;
        }

        if (Page is not null && shown.Count > 0)
        {
            await ResultsPage.WriteAsync(
                Page, [(Axis == Workload.Take ? "take" : "write", Section(shown, declined, written))]).ConfigureAwait(false);
        }

        if (!check)
        {
            return 0;
        }

        // A CONFIRMING CHILD ONLY REPORTS; the parent decides. These lines are what it parses.
        if (IsConfirming)
        {
            foreach (string name in over)
            {
                Console.Out.WriteLine($"{FailPrefix}{name}");
            }

            return 0;
        }

        if (over.Count > 0)
        {
            over = await ConfirmAsync(over, failures).ConfigureAwait(false);
        }

        Console.Out.WriteLine(
            over.Count == 0
                ? "Every encoding is inside its ceiling."
                : $"{over.Count} encoding(s) above ceiling in TWO processes. A ratio only moves " +
                  "when the code moves: find the change, do not raise the ceiling.");
        return over.Count == 0 ? 0 : 1;
    }

    /// <summary>True when this process is the second opinion, not the one that decides.</summary>
    private static bool IsConfirming =>
        Environment.GetEnvironmentVariable(ConfirmVariable) == "1";

    /// <summary>The take or the write axis per encoding, for the page's <c>take</c> or <c>write</c> section.</summary>
    /// <param name="shown">Every file both sides measured, in order.</param>
    /// <param name="declined">The files the reference declines to write.</param>
    /// <param name="written">On the write axis, the bytes each writer produced per file.</param>
    private static string Section(
        List<(string Encoding, Measurement Measured)> shown, List<string> declined,
        Dictionary<string, (long Ours, long Theirs)> written)
    {
        bool take = Axis == Workload.Take;
        StringBuilder text = new StringBuilder();
        text.AppendLine(take ? "## Taking rows, per encoding" : "## Writing, per encoding");
        text.AppendLine();
        text.AppendLine(take
            ? string.Create(CultureInfo.InvariantCulture,
                $"The files of the per-encoding corpus again, {TakeCount} rows spread evenly over each, one every {TakeStride:N0}: what a")
            : "The files of the per-encoding corpus again, each read and written back out to a sink that");
        text.AppendLine(take
            ? "decoder costs to reach a few rows rather than all of them."
            : "keeps nothing, on both sides, both writers given the rows as our reader delivers them, decoded and a");
        if (!take)
        {
            text.AppendLine("constant kept as one value: what a writer costs, the read included on both sides.");
        }

        text.AppendLine("Each call opens the file and maps it anew, on both sides.");
        text.AppendLine("Both implementations in one process, Rust's through a C ABI, taking turns against one clock:");
        text.AppendLine(string.Create(CultureInfo.InvariantCulture,
            $"at least {MinRounds} rounds after a {WarmupBudget.TotalSeconds:F0}-second warm-up per file, our side on the JIT, warmed."));
        if (!take)
        {
            text.AppendLine("A writer can be fast by compressing less, so each one's bytes are beside its time.");
        }

        text.AppendLine();
        text.AppendLine(take
            ? "| encoding | Vorticity, µs | Vortex Rust, µs | speedup |"
            : "| encoding | Vorticity, µs | Vortex Rust, µs | speedup | Vorticity, bytes | Vortex Rust, bytes |");
        text.AppendLine(take ? "|---|---:|---:|---:|" : "|---|---:|---:|---:|---:|---:|");
        foreach ((string encoding, Measurement m) in shown)
        {
            string bytes = take
                ? string.Empty
                : written.TryGetValue(encoding, out (long Ours, long Theirs) size)
                    ? string.Create(CultureInfo.InvariantCulture, $" {size.Ours:N0} | {size.Theirs:N0} |")
                    : " — | — |";
            text.AppendLine(string.Create(CultureInfo.InvariantCulture,
                $"| `{encoding}` | {m.Ours:N0} | {m.Theirs:N0} | {ResultsPage.Speedup(m.Speedup.Median)} |{bytes}"));
        }

        text.AppendLine();
        List<double> speedups = [.. shown.Select(s => s.Measured.Speedup.Median)];
        speedups.Sort();
        double median = speedups.Count % 2 == 1
            ? speedups[speedups.Count / 2]
            : (speedups[(speedups.Count / 2) - 1] + speedups[speedups.Count / 2]) / 2;
        List<(string Encoding, Measurement Measured)> behind =
            [.. shown.Where(s => s.Measured.Speedup.Median <= 1).OrderBy(s => s.Measured.Speedup.Median)];
        text.Append(string.Create(CultureInfo.InvariantCulture,
            $"Vorticity took less time on {shown.Count - behind.Count} of {shown.Count} files; the median speedup is {ResultsPage.Speedup(median)}."));
        text.AppendLine(behind.Count == 0
            ? string.Empty
            : string.Create(CultureInfo.InvariantCulture,
                $" At 1.00x or below: {string.Join(", ", behind.Select(b => $"`{b.Encoding}` {ResultsPage.Speedup(b.Measured.Speedup.Median)}"))}."));
        List<string> perChunk = [.. shown.Where(s => s.Measured.Split == RustReader.SplitPerChunk).Select(s => $"`{s.Encoding}`")];
        List<string> byDefault = [.. shown.Where(s => s.Measured.Split != RustReader.SplitPerChunk).Select(s => $"`{s.Encoding}`")];
        text.AppendLine(string.Create(CultureInfo.InvariantCulture,
            $"Rust is timed under the faster of its two splits, file by file: one split per chunk on {perChunk.Count} of {shown.Count} files, its default on {Report.Fewer(perChunk, byDefault)}."));
        if (!take && written.Count > 0)
        {
            List<(string Encoding, double Ratio)> sizes = [.. written
                .Where(w => w.Value.Theirs > 0)
                .Select(w => (w.Key, (double)w.Value.Ours / w.Value.Theirs))];
            List<(string Encoding, double Ratio)> larger = [.. sizes.Where(s => s.Ratio > 1.05).OrderByDescending(s => s.Ratio)];
            // In times, not with an x: on a page where an x is a speedup, more bytes would read as faster.
            string above = larger.Count == 0
                ? "."
                : "; more than 5 % above them on " + string.Join(", ", larger.Select((l, i) =>
                    $"`{l.Encoding}` ({ResultsPage.Figure(l.Ratio)} times{(i == 0 ? " Rust's" : string.Empty)})")) + ".";
            text.AppendLine(string.Create(CultureInfo.InvariantCulture,
                $"Vorticity's bytes were within 5 % of Rust's or fewer on {sizes.Count - larger.Count} of {sizes.Count} files{above}"));
        }

        if (declined.Count > 0)
        {
            text.AppendLine(string.Create(CultureInfo.InvariantCulture,
                $"Rust's writer declines {string.Join(", ", declined.Select(d => $"`{d}`"))}, which is left out."));
        }

        text.AppendLine();
        text.AppendLine(ResultsPage.Provenance(
            $"Vortex 0.86.1 through the C ABI of `tools/vxbench-rs`, binary {RustReader.Fingerprint ?? "unknown"}"));
        return text.ToString();
    }

    /// <summary>
    /// Re-measures the whole axis in a FRESH PROCESS and keeps only the encodings over the ceiling
    /// in both.
    /// </summary>
    /// <param name="over">What this process found over the ceiling.</param>
    /// <param name="failures">The prose lines for those, printed when they are confirmed.</param>
    /// <returns>The encodings over in both processes.</returns>
    /// <remarks>
    /// THE DRIFT THIS DEFEATS IS BETWEEN PROCESSES, not inside one. Three consecutive runs put three
    /// DIFFERENT axes over the ceiling with no code change between them, and the axis of the second
    /// came back on its own: `fastlanes_bitpacked` 1.30 -> 1.64 -> 1.24. The mechanism is visible in
    /// the columns -- ours rose 9 % while the reference's fell 12 %, and a ratio takes both drifts
    /// the same way -- so a margin of 15 % cannot separate it from a regression. Two further pairs
    /// were measured on 2026-09-15, minutes apart.
    /// <para>
    /// WHY THE WHOLE AXIS AND NOT THE OFFENDING FILES. Narrowing changes the number: the same
    /// bytes measured +32 % on our side when one file is run alone. A confirmation on a
    /// narrowed run would be a different measurement wearing the same name.
    /// </para>
    /// <para>
    /// The cost is paid only when something fails, and it is the only honest way to keep the gate:
    /// a verdict that depends on a draw is not a verdict.
    /// </para>
    /// </remarks>
    private static async Task<List<string>> ConfirmAsync(List<string> over, List<string> failures)
    {
        Console.Out.WriteLine(
            $"\n{over.Count} encoding(s) over the ceiling. Confirming in a second process, because " +
            "between-run drift on the short axes is larger than the x1.15 margin:");
        failures.ForEach(Console.Out.WriteLine);

        string? self = Environment.ProcessPath;
        if (self is null)
        {
            Console.Error.WriteLine(
                "No process path; cannot confirm, so the first reading stands.");
            return over;
        }

        ProcessStartInfo start = new ProcessStartInfo(self)
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
        };
        start.ArgumentList.Add("--throughput");
        if (Axis != Workload.Scan)
        {
            start.ArgumentList.Add(Axis == Workload.Take ? "--take" : "--write");
        }

        start.ArgumentList.Add("--check");
        start.Environment[ConfirmVariable] = "1";

        using Process child = Process.Start(start)
            ?? throw new InvalidOperationException("Could not start the confirming run.");
        string output = await child.StandardOutput.ReadToEndAsync().ConfigureAwait(false);
        string errors = await child.StandardError.ReadToEndAsync().ConfigureAwait(false);
        await child.WaitForExitAsync().ConfigureAwait(false);
        if (child.ExitCode != 0)
        {
            Console.Error.WriteLine(
                $"The confirming run failed ({child.ExitCode}), so the first reading stands:\n{errors}");
            return over;
        }

        HashSet<string> again = [];
        foreach (string line in output.Split('\n'))
        {
            if (line.StartsWith(FailPrefix, StringComparison.Ordinal))
            {
                again.Add(line[FailPrefix.Length..].Trim());
            }
        }

        List<string> both = [.. over.Where(again.Contains)];
        List<string> once = [.. over.Where(name => !again.Contains(name))];
        if (once.Count > 0)
        {
            Console.Out.WriteLine(
                $"  not reproduced in the second process, so not a failure: {string.Join(", ", once)}");
        }

        return both;
    }

    /// <summary>The reference ratio for one encoding, or null when it has none yet.</summary>
    /// <param name="encoding">The file's base name.</param>
    private static Reference? ReferenceFor(string encoding)
    {
        foreach (Reference reference in ActiveReferences)
        {
            if (string.Equals(reference.Encoding, encoding, StringComparison.Ordinal))
            {
                return reference;
            }
        }

        return null;
    }

    /// <summary>One encoding's ratchet: the ratio it was measured at, and how far its passes fell.</summary>
    /// <param name="Encoding">The encoding, as the corpus names it.</param>
    /// <param name="Ratio">The ratio the ceiling is built on.</param>
    /// <param name="Spread">
    /// How far apart the calibration passes fell, as a fraction of <paramref name="Ratio"/>. An
    /// encoding added by hand leaves it at zero and falls back on the flat margin until a
    /// recalibration measures one.
    /// </param>
    /// <remarks>
    /// These axes are shorter and far more numerous than the ratio gate's, and their dispersion is
    /// the reason a run pins a different set of encodings than the run before it. A ceiling drawn
    /// from each encoding's own dispersion says what that encoding can actually resolve; a flat one
    /// says every encoding resolves the same change, which is not true of a five-microsecond axis
    /// and a fifty-millisecond one.
    /// </remarks>
    internal readonly record struct Reference(string Encoding, double Ratio, double Spread = 0);

    /// <summary>Times both readers on one file, interleaved, until the ratio's interval is tight.</summary>
    /// <remarks>
    /// The same three changes as `RatioCheck`, for the same reason: the ratio is
    /// taken PER ROUND because the rounds are paired, the rounds keep coming until the bootstrapped
    /// interval is tight enough or the budget is spent, and a scan shorter than
    /// <see cref="MinRoundMicroseconds"/> is repeated inside one timed round.
    /// </remarks>
    private static async Task<Measurement> MeasureAsync(string path, bool rust)
    {
        long deadline = Stopwatch.GetTimestamp() +
            (long)(WarmupBudget.TotalSeconds * Stopwatch.Frequency);
        double lastOurs = 0;
        double lastTheirs = 0;
        do
        {
            lastOurs = await TimeAsync(path, 1).ConfigureAwait(false);
            lastTheirs = rust ? Time(path, 1) : 0;
        }
        while (Stopwatch.GetTimestamp() < deadline);

        // The reference's faster split on this file, once both are warm: see RustReader.FasterSplit.
        long split = rust ? RustReader.FasterSplit(() => Theirs(path), SplitRounds) : RustReader.SplitDefault;
        if (rust)
        {
            lastTheirs = Time(path, 1);
        }

        int repeats = Repeats(Math.Max(lastOurs, lastTheirs));
        int minimum = Math.Max(lastOurs, lastTheirs) >= LongRoundSeconds * 1_000_000
            ? LongMinRounds
            : MinRounds;

        List<double> ratios = [];
        List<double> speedups = [];
        List<double> mine = [];
        List<double> theirs = [];
        long stop = Stopwatch.GetTimestamp() + (long)(Budget * Stopwatch.Frequency);
        Interval interval = default;
        for (int round = 0; round < MaxRounds; round++)
        {
            double ours;
            double rustTime;

            // Alternating, for RatioCheck's reason: a fixed order gives one side the cache-cold
            // cost every round, which is a stable bias and therefore worse than noise.
            if (round % 2 == 0)
            {
                ours = await TimeAsync(path, repeats).ConfigureAwait(false);
                rustTime = rust ? Time(path, repeats) : 0;
            }
            else
            {
                rustTime = rust ? Time(path, repeats) : 0;
                ours = await TimeAsync(path, repeats).ConfigureAwait(false);
            }

            mine.Add(ours);
            theirs.Add(rustTime);
            ratios.Add(rustTime == 0 ? 0 : ours / rustTime);
            speedups.Add(ours == 0 ? 0 : rustTime / ours);

            if (round + 1 >= minimum)
            {
                interval = Statistics.Bootstrap(
                    System.Runtime.InteropServices.CollectionsMarshal.AsSpan(ratios));
                if (!rust || interval.MinimumDetectableEffect <= Precision ||
                    Stopwatch.GetTimestamp() >= stop)
                {
                    break;
                }
            }
        }

        if (rust)
        {
            RustReader.Require(RustReader.SetSplit(RustReader.SplitDefault), "split");
        }

        // The page's figure is the same rounds read the other way, bootstrapped on their own: the
        // inverse of a median of an even count is not the median of the inverses.
        Interval speedup = Statistics.Bootstrap(System.Runtime.InteropServices.CollectionsMarshal.AsSpan(speedups));
        return new Measurement(Median([.. mine]), Median([.. theirs]), interval, speedup, repeats, split);
    }

    /// <summary>One file measured: both readers, the ratio's interval, and how it was timed.</summary>
    /// <param name="Ratio">The median per-round ratio, ours over Rust's, and its 95% interval: what the gate holds.</param>
    /// <param name="Speedup">The median per-round speedup, Rust's time over ours: what the page prints.</param>
    /// <param name="Split">The reference's split the file was timed under, the faster of its two.</param>
    private readonly record struct Measurement(
        double Ours, double Theirs, Interval Ratio, Interval Speedup, int Repeats, long Split);

    /// <summary>Scans per timed round, so that one round clears the timer's noise floor.</summary>
    private static int Repeats(double microseconds) =>
        microseconds <= 0 ? 1 : Math.Max(1, (int)Math.Ceiling(MinRoundMicroseconds / microseconds));

    /// <summary>Microseconds per scan, timing <paramref name="repeats"/> of them as one round.</summary>
    private static async Task<double> TimeAsync(string path, int repeats)
    {
        long start = Stopwatch.GetTimestamp();
        for (int i = 0; i < repeats; i++)
        {
            await OursAsync(path).ConfigureAwait(false);
        }

        return Stopwatch.GetElapsedTime(start).TotalMicroseconds / repeats;
    }

    /// <summary>Microseconds per scan, timing <paramref name="repeats"/> of them as one round.</summary>
    private static double Time(string path, int repeats)
    {
        long start = Stopwatch.GetTimestamp();
        for (int i = 0; i < repeats; i++)
        {
            Theirs(path);
        }

        return Stopwatch.GetElapsedTime(start).TotalMicroseconds / repeats;
    }

    private static double Median(double[] values)
    {
        double[] copy = (double[])values.Clone();
        Array.Sort(copy);
        return copy[copy.Length / 2];
    }

    /// <summary>
    /// The drift between runs an encoding is held to on the current axis, or zero.
    /// </summary>
    private static double DriftOf(string encoding)
    {
        if (Axis != Workload.Scan)
        {
            return 0;
        }

        foreach ((string name, double spread) in ReadDrift)
        {
            if (string.Equals(name, encoding, StringComparison.Ordinal))
            {
                return spread;
            }
        }

        return 0;
    }

    /// <summary>The ratchet table of the current axis.</summary>
    private static Reference[] ActiveReferences => Axis switch
    {
        Workload.Take => TakeReferences,
        Workload.Write => WriteReferences,
        _ => References,
    };

    /// <summary>Our side of the current axis.</summary>
    private static Task<long> OursAsync(string path) => Axis switch
    {
        Workload.Take => Scenarios.ScatteredTake(path, TakeCount, TakeStride),
        Workload.Write => Scenarios.ReadAndWrite(path),
        _ => Scenarios.ScanAll(path),
    };

    /// <summary>The reference's side of the current axis.</summary>
    private static long Theirs(string path) => Axis switch
    {
        Workload.Take => RustReader.Require(RustReader.Take(path, TakeCount, TakeStride), "take"),
        Workload.Write => RustReader.Require(RustReader.Write(path), "write"),
        _ => RustReader.Require(RustReader.ScanCanonical(path), "scan"),
    };

    private static Task<long> ScanAll(string path) => Scenarios.ScanAll(path);

    /// <summary>
    /// Batches the scan emits, reported beside the timing because it is what explains it.
    /// </summary>
    /// <param name="path">The file to count.</param>
    /// <remarks>
    /// A file written as ONE chunk of a million rows is read as ~977 batches, and this axis exists
    /// because that ratio is where the cost lives. Reporting the count turns "the number is large"
    /// into "the number is large FOR THIS REASON".
    /// </remarks>
    private static async Task<long> CountBatches(string path)
    {
        await using VortexFile file = await VortexFile.OpenAsync(path, CancellationToken.None);
        long batches = 0;
        await foreach (RecordBatch batch in file.ScanBuilder().ExecuteAsync()
            .WithCancellation(CancellationToken.None))
        {
            batches++;
        }

        return batches;
    }
}

