/// <summary>Per-encoding decode throughput in nanoseconds per value.</summary>
internal static class ThroughputCheck
{
    /// <summary>The environment variable naming the generated input directory.</summary>
    private const string Variable = "VORTICITY_THROUGHPUT_CORPUS";

    /// <summary>
    /// Where the inputs live when the variable is unset.
    /// </summary>
    /// <remarks>
    /// NOT `/tmp`. 330 MB that takes minutes to regenerate, wiped by a reboot on macOS and by
    /// tmpfiles on Linux, is a corpus that gets regenerated by accident -- and a regenerated corpus
    /// is exactly what the manifest exists to detect. A cache directory is the right place for a
    /// large derived artifact that is expensive to rebuild and safe to delete.
    /// </remarks>
    private static string DefaultRoot => Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.UserProfile),
        ".cache", "vorticity", "throughput-1M");

    /// <summary>The generated input directory: the variable's, or the default.</summary>
    internal static string Root =>
        Environment.GetEnvironmentVariable(Variable) is { Length: > 0 } configured ? configured : DefaultRoot;

    /// <summary>The row count every reference in <see cref="References"/> was measured at.</summary>
    private const long ReferenceRows = 1_000_000;

    /// <summary>The manifest shapes this build knows how to read.</summary>
    private const string ManifestFormat = "vorticity-throughput-corpus/1";

    /// <summary>The prefix a recalibration pass prints its measurements under.</summary>
    private const string PassPrefix = "PASS\t";

    /// <summary>The prefix one over-ceiling encoding is printed under, for the confirming run.</summary>
    private const string FailPrefix = "FAIL\t";

    /// <summary>Set on the confirming child so it does not spawn one of its own.</summary>
    private const string ConfirmVariable = "VORTICITY_BENCH_CONFIRM";

    /// <summary>What the axis times on each side.</summary>
    internal enum Workload
    {
        /// <summary>Every row of the file, canonicalized. The default.</summary>
        Scan,

        /// <summary>
        /// <see cref="TakeCount"/> rows spread evenly over the file, canonicalized.
        /// </summary>
        /// <remarks>
        /// Ten decoders have a `DecodeSelected` and nine do not, and nothing
        /// measured the selective path anywhere but on two files of 4 096 rows. `--ratio-check`'s
        /// `scattered take` axis is one file; this is the same question asked of every encoding.
        /// </remarks>
        Take,

        /// <summary>The file read back and written out to a sink that keeps nothing.</summary>
        /// <remarks>
        /// `--ratio-check`'s `read and write back` axis sees ONE input shape,
        /// a 65 536-row file, and the compressor chooses per column -- so a writer regression on a
        /// string column, or on a column whose best candidate is a dictionary, has nowhere to show.
        /// The read is on both sides and is therefore common-mode, but it is not small: subtract
        /// the scan axis from both before reading the quotient as a statement about writers.
        /// </remarks>
        Write,
    }

    /// <summary>Which workload this invocation measures.</summary>
    internal static Workload Axis { get; set; } = Workload.Scan;

    /// <summary>
    /// The benchmark page to write the take or the write axis to, as its <c>take</c> or
    /// <c>write</c> section, or null. Only a run of every file writes it; the scan axis is on the
    /// page as the report measures it, each side in a process of its own.
    /// </summary>
    internal static string? Page { get; set; }

    /// <summary>The field a recalibrated table is pasted into.</summary>
    private static string TableName => Axis switch
    {
        Workload.Take => "TakeReferences",
        Workload.Write => "WriteReferences",
        _ => "References",
    };

    /// <summary>Rows a take asks for.</summary>
    /// <remarks>
    /// Sixty-four, as in `RatioCheck`, but the stride SPREADS them over the whole file rather than
    /// packing them into its first 65 536 rows: a take that never leaves the first split measures
    /// one split's decode, not the skipping that makes a take worth having.
    /// </remarks>
    private const long TakeCount = 64;

    /// <summary>The gap between taken rows, so the last one is near the end of the file.</summary>
    private static long TakeStride => Math.Max(1, ReferenceRows / TakeCount);

    /// <summary>Runs each recalibration pass in its own process, then prints the table.</summary>
    /// <param name="rebaseFrom">
    /// The reference binary the table was set under, or null. When given, every pass is a pair of
    /// processes, one under it and one under the running binary, and each reference moves by what
    /// the binary moved its ratio: see `RatioCheck.CarryAsync`.
    /// </param>
    private static async Task<int> RecalibrateAcrossProcessesAsync(
        string[] only, int passes, bool rebase, bool hold, string? rebaseFrom)
    {
        Console.Out.WriteLine(
            $"RECALIBRATE: {passes} PROCESSES. Nothing is gated; paste the table below into " +
            $"ThroughputCheck.{TableName}.");
        if (rebaseFrom is not null)
        {
            if (RustReader.FingerprintOf(rebaseFrom) is not { } old)
            {
                Console.Error.WriteLine($"--rebase-from: no reference binary at {rebaseFrom}.");
                return 2;
            }

            Console.Out.WriteLine(
                $"  carried from {old} to the running {RustReader.Fingerprint ?? "unknown"}: every pass " +
                "runs under both.");
        }

        string self = Environment.ProcessPath
            ?? throw new InvalidOperationException("No process path; cannot re-run for a pass.");
        Dictionary<string, List<double>> measured = [];
        Dictionary<string, List<double>> before = [];
        Dictionary<string, bool> grouped = [];
        List<(int Pass, bool UnderOld)> runs = [];
        for (int pass = 1; pass <= passes; pass++)
        {
            bool oldFirst = pass % 2 == 1;
            if (rebaseFrom is not null && oldFirst)
            {
                runs.Add((pass, true));
            }

            runs.Add((pass, false));
            if (rebaseFrom is not null && !oldFirst)
            {
                runs.Add((pass, true));
            }
        }

        foreach ((int pass, bool underOld) in runs)
        {
            ProcessStartInfo start = new ProcessStartInfo(self)
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
            };
            if (underOld)
            {
                start.Environment["VORTICITY_VXBENCH"] = rebaseFrom;
            }

            start.ArgumentList.Add("--throughput");
            if (Axis != Workload.Scan)
            {
                start.ArgumentList.Add(Axis == Workload.Take ? "--take" : "--write");
            }

            foreach (string family in only)
            {
                start.ArgumentList.Add(family);
            }

            start.ArgumentList.Add("--check");
            start.ArgumentList.Add("--recalibrate");
            start.ArgumentList.Add("1");

            using Process child = Process.Start(start)
                ?? throw new InvalidOperationException("Could not start a pass.");
            string output = await child.StandardOutput.ReadToEndAsync().ConfigureAwait(false);
            string errors = await child.StandardError.ReadToEndAsync().ConfigureAwait(false);
            await child.WaitForExitAsync().ConfigureAwait(false);
            if (child.ExitCode != 0)
            {
                Console.Error.WriteLine($"Pass {pass} failed ({child.ExitCode}):\n{errors}");
                return child.ExitCode;
            }

            int seen = 0;
            foreach (string line in output.Split('\n'))
            {
                if (!line.StartsWith(PassPrefix, StringComparison.Ordinal))
                {
                    continue;
                }

                string[] parts = line[PassPrefix.Length..].Split('\t');
                if (parts.Length != 3 ||
                    !double.TryParse(parts[1], CultureInfo.InvariantCulture, out double median))
                {
                    continue;
                }

                Dictionary<string, List<double>> into = underOld ? before : measured;
                if (!into.TryGetValue(parts[0], out List<double>? values))
                {
                    values = [];
                    into[parts[0]] = values;
                }

                values.Add(median);
                if (!underOld)
                {
                    grouped[parts[0]] = parts[2].Trim() == "1";
                }

                seen++;
            }

            if (seen == 0)
            {
                Console.Error.WriteLine($"Pass {pass} measured nothing.\n{errors}");
                return 2;
            }

            Console.Out.WriteLine(
                $"  pass {pass} of {passes}{(underOld ? ", under the old binary" : string.Empty)}: {seen} encoding(s).");
        }

        return PrintRecalibration(measured, grouped, passes, rebase, hold, rebaseFrom is null ? null : before);
    }

    /// <summary>
    /// Prints a replacement <see cref="References"/> table from several measured passes.
    /// </summary>
    /// <remarks>
    /// The same rules as `RatioCheck.RecalibrateAsync`, and for the same reasons: the MEDIAN of each
    /// pass rather than its interval's top, because uncertainty is applied once at the decision and
    /// folding it in here too would buy the same protection twice; the max over passes, because a
    /// ceiling set from an average goes red on half the runs that produced it; and a value that
    /// would RISE is printed back unchanged unless `--rebase` and the estimator changed: the
    /// encoding now groups scans into a round, or the reference binary is not the one the tables
    /// name.
    /// <para>
    /// `--hold` prints EVERY reference back unchanged and refreshes only the dispersion. It is the
    /// mode for the run that is not deciding anything: the ceilings follow the machine, the
    /// references stay where the last decision put them, and every number on a pasted line -- the
    /// reference, the band and the dispersion -- comes from one run, so the line can be read
    /// against the log that produced it.
    /// </para>
    /// <para>
    /// THREE PASSES, AND NOT MORE, AND THE REASON IS NOT COST. Measured over this whole table, nine
    /// passes double the median dispersion (0.035 to 0.073) and grow it on fifty-one axes of
    /// fifty-seven; ten then exceed the flat margin where none did. That looks like three passes
    /// under-reporting, and for scatter it partly is, but the largest figures are not scatter at
    /// all: `dict` spans 0.96-1.40 with nine passes of nine above its reference, `alprd` 1.32-1.62
    /// with nine of nine. A band that only climbs is a level that moved, and `(max - min)` cannot
    /// tell the two apart -- so widening a ceiling by it would spend a longer observation window on
    /// hiding exactly what the window revealed.
    ///
    /// Axis length does not predict it either, which was the other guess: the median dispersion
    /// runs 0.079 under a hundred microseconds and 0.067 over two milliseconds, flat across the
    /// range. What the count of passes above the reference says is the usable signal, and it is
    /// already printed on every line.
    /// </para>
    /// </remarks>
    private static int PrintRecalibration(
        Dictionary<string, List<double>> measured,
        Dictionary<string, bool> grouped,
        int passes,
        bool rebase,
        bool hold,
        Dictionary<string, List<double>>? before)
    {
        Reference[] table = ActiveReferences;
        Console.Out.WriteLine(
            $"\nRECALIBRATE: {passes} passes, max of the per-pass medians. Paste into " +
            $"ThroughputCheck.{TableName}.");

        // A reference binary other than the one the tables name is a new denominator under every
        // encoding, which a rebase may follow as it follows a grouped round.
        bool newBinary = !string.Equals(RustReader.Fingerprint, CalibratedShim, StringComparison.Ordinal);
        int held = 0;
        int rebased = 0;
        int declined = 0;
        int carried = 0;
        foreach ((string name, double current, double spread) in table)
        {
            if (!measured.TryGetValue(name, out List<double>? seen) || seen.Count == 0)
            {
                Console.Out.WriteLine(string.Create(
                    CultureInfo.InvariantCulture,
                    $"        new(\"{name}\", {Ref(current)}, {spread:F3}),   // not measured this run"));
                continue;
            }

            double max = seen.Max();
            double min = seen.Min();
            if (before is not null && before.TryGetValue(name, out List<double>? under) && under.Count > 0
                && under.Max() is var was and > 0)
            {
                // Carried: the reference moves by what the binary moved the ratio, our side being the
                // same build under both, so whatever it held against our code it still holds.
                double factor = max / was;
                carried++;
                Console.Out.WriteLine(string.Create(
                    CultureInfo.InvariantCulture,
                    $"        new(\"{name}\", {Ref(current * factor)}, {(max > 0 ? (max - min) / max : 0):F3}),   " +
                    $"// {passes} passes, spread {Ref(min)}-{Ref(max)}; carried from {Ref(current)}, " +
                    $"{factor - 1:+0.0%;-0.0%;0.0%} under the new binary ({Ref(was)} -> {Ref(max)})"));
                continue;
            }
            bool changedEstimator = rebase && (grouped.GetValueOrDefault(name) || newBinary);
            bool loosens = hold || (max >= current && !changedEstimator);
            double value = loosens ? current : max;
            rebased += !loosens && max > current ? 1 : 0;
            // HOW MANY PASSES WERE ABOVE, not just the peak. One pass above out
            // of three is drift; three out of three is a reference the axis cannot reach, and only
            // the second is worth a deliberate edit. HELD used to print the peak alone, which reads
            // the same in both cases.
            int above = seen.Count(value => value > current);
            string note;
            if (loosens && max >= current)
            {
                held++;
                note = string.Create(
                    CultureInfo.InvariantCulture,
                    $"HELD at {Ref(current)}: {above} of {passes} passes above, peak {Ref(max)}, no loosening");
            }
            else if (loosens)
            {
                // `--hold` declining a DROP, which is the mode's whole point: the run refreshes the
                // dispersion without spending the decision of where the reference belongs.
                declined++;
                note = string.Create(
                    CultureInfo.InvariantCulture,
                    $"HELD at {Ref(current)} by --hold: peak {Ref(max)}, " +
                    $"{(max / current) - 1:+0.0%;-0.0%;0.0%} not taken");
            }
            else if (max > current)
            {
                note = string.Create(
                    CultureInfo.InvariantCulture,
                    $"REBASED UP from {Ref(current)} ({(newBinary ? "a new reference binary" : "k>1")}): " +
                    $"{(max / current) - 1:+0.0%}");
            }
            else
            {
                note = string.Create(
                    CultureInfo.InvariantCulture, $"was {Ref(current)}, {(max / current) - 1:+0.0%;-0.0%;0.0%}");
            }

            // The dispersion the passes showed, as a fraction of the value the ceiling is built on.
            // Emitted rather than described: a number in a comment cannot widen a ceiling.
            double measuredSpread = value > 0 ? (max - min) / value : 0;
            Console.Out.WriteLine(string.Create(
                CultureInfo.InvariantCulture,
                $"        new(\"{name}\", {Ref(value)}, {measuredSpread:F3}),   " +
                $"// {passes} passes, spread {Ref(min)}-{Ref(max)}; {note}"));
        }

        // An axis calibrated for the first time has an empty table, so every name it measured is
        // new. Printing them here is what makes `--recalibrate` the way a new axis gets its
        // ratchets, instead of fifty numbers copied by hand out of a report.
        HashSet<string> known = [.. table.Select(entry => entry.Encoding)];
        foreach ((string name, List<double> seen) in measured.OrderBy(e => e.Key, StringComparer.Ordinal))
        {
            if (known.Contains(name) || seen.Count == 0)
            {
                continue;
            }

            double first = seen.Max() > 0 ? (seen.Max() - seen.Min()) / seen.Max() : 0;
            Console.Out.WriteLine(string.Create(
                CultureInfo.InvariantCulture,
                $"        new(\"{name}\", {Ref(seen.Max())}, {first:F3}),   // {passes} passes, spread " +
                $"{Ref(seen.Min())}-{Ref(seen.Max())}; first calibration"));
        }

        Console.Out.WriteLine(
            $"\n{held} held (measured above their reference, printed back unchanged), " +
            $"{declined} held by --hold over a drop the calibration read, " +
            $"{rebased} rebased for a changed estimator, {carried} carried to the running binary.");

        // The table and the binary it was measured through belong to the same paste. A table
        // recorded without one cannot be told apart later from a binary that moved under it.
        Console.Out.WriteLine(
            $"\nPaste alongside it, into ThroughputCheck.CalibratedShim:\n" +
            $"    private static readonly string? CalibratedShim = \"{RustReader.Fingerprint ?? "unknown"}\";");
        return 0;
    }

    /// <summary>What produced a set of inputs, as `manifest.json` records it.</summary>
    internal sealed record Manifest(
        string? Format, long Rows, string? Vortex, Manifest.Origin? Generator, Manifest.Entry[]? Files)
    {
        /// <summary>The generator's working tree.</summary>
        internal sealed record Origin(string? Commit, bool Dirty);

        /// <summary>One generated file.</summary>
        internal sealed record Entry(string? Id, long Bytes, string? Sha256);
    }

    /// <summary>Reads `manifest.json` beside the inputs.</summary>
    /// <param name="root">The input directory.</param>
    /// <param name="problem">Why there is no usable manifest, when null is returned.</param>
    /// <remarks>
    /// Every refusal names the row count or the format it found, because the useful failure here is
    /// not "no manifest" but "this is a corpus of a different shape than the one your references
    /// were measured on".
    /// </remarks>
    private static Manifest? ReadManifest(string root, out string problem)
    {
        string path = Path.Combine(root, "manifest.json");
        if (!System.IO.File.Exists(path))
        {
            problem = $"no manifest.json under {root}";
            return null;
        }

        Manifest? manifest;
        try
        {
            manifest = JsonSerializer.Deserialize(
                System.IO.File.ReadAllText(path),
                ManifestContext.Default.Manifest);
        }
        catch (JsonException e)
        {
            problem = $"{path} is not readable as a manifest: {e.Message}";
            return null;
        }

        if (manifest is null)
        {
            problem = $"{path} is empty";
            return null;
        }

        if (manifest.Format != ManifestFormat)
        {
            problem = $"{path} is `{manifest.Format}`; this build reads `{ManifestFormat}`";
            return null;
        }

        if (manifest.Rows != ReferenceRows)
        {
            problem =
                $"{path} says {manifest.Rows} rows per file; every reference in this file was " +
                $"measured at {ReferenceRows}. A ns/value figure at another length is a different " +
                "measurement under the same name";
            return null;
        }

        problem = string.Empty;
        return manifest;
    }

    /// <summary>
    /// Checks that the files about to be measured are the ones the manifest describes.
    /// </summary>
    /// <returns>The complaint, or null when every file matches.</returns>
    /// <remarks>
    /// ONLY THE SELECTED FILES are hashed: `--throughput fsst --check` should not read 330 MB to
    /// measure 12. Hashing what it does measure costs about a second for the full set, which is
    /// nothing beside the 54 s of measurement it protects.
    /// </remarks>
    private static string? VerifyAgainstManifest(Manifest manifest, string[] files, string root)
    {
        Dictionary<string, Manifest.Entry> byId = [];
        foreach (Manifest.Entry entry in manifest.Files ?? [])
        {
            if (entry.Id is not null)
            {
                byId[entry.Id] = entry;
            }
        }

        List<string> problems = [];
        foreach (string file in files)
        {
            string id = Path.GetFileNameWithoutExtension(file);
            if (!byId.TryGetValue(id, out Manifest.Entry? entry))
            {
                problems.Add($"  {id}: present on disk, absent from the manifest");
                continue;
            }

            string actual = Convert.ToHexStringLower(SHA256.HashData(System.IO.File.ReadAllBytes(file)));
            if (!string.Equals(actual, entry.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                problems.Add($"  {id}: sha256 {actual[..16]}... against the manifest's {entry.Sha256?[..16]}...");
            }
        }

        return problems.Count == 0
            ? null
            : $"{problems.Count} file(s) do not match {Path.Combine(root, "manifest.json")}:\n" +
              string.Join("\n", problems) +
              "\nThe references are ratchets against the manifest's bytes. Regenerate with " +
              "bench/gen-throughput.sh, then recalibrate if the numbers move.";
    }

    /// <summary>A commit, short enough to read in a report.</summary>
    private static string Shorten(string? commit) =>
        string.IsNullOrEmpty(commit) ? "an unknown tree"
            : commit.Length <= 7 ? commit
            : commit[..7];

    /// <summary>Wall-clock warm-up per file, for the same reason RatioCheck uses one.</summary>
    private static TimeSpan WarmupBudget => TimeSpan.FromSeconds(Quick ? 0.3 : 1.0);

    /// <summary>Calls per split, and per file, that decide which of the reference's splits it is timed under.</summary>
    private static int SplitRounds => Quick ? 3 : 5;

    /// <summary>
    /// Rounds measured before the interval is consulted.
    /// </summary>
    /// <remarks>
    /// Seven was a fixed count, and this is what a fixed count costs: at a million rows a scan is
    /// milliseconds, but a ratio out of seven paired rounds has an interval wider than the x1.15
    /// margin on the cheap encodings, which is how this gate failed two invocations in four with
    /// nothing changed. Rounds are adaptive now -- this is the floor, and <see cref="Precision"/>
    /// decides when to stop.
    /// </remarks>
    private const int MinRounds = 9;

    /// <summary>
    /// The floor on rounds once one round costs more than <see cref="LongRoundSeconds"/>.
    /// </summary>
    /// <remarks>
    /// The write axis is not a microsecond axis: reading a million rows back out costs 28 ms on
    /// `dict_u8_codes` and 13.2 SECONDS on `fsst`, where our compressor trains a symbol table on a
    /// million strings. Nine rounds of that is two minutes for one file, and a gate nobody waits
    /// for is a gate nobody runs. Five paired rounds on a thirteen-second workload still
    /// resolve a few percent, because the thing being measured is nothing like the timer's floor.
    /// </remarks>
    private const int LongMinRounds = 5;

    /// <summary>Above this, a round is long enough that the round count is the cost.</summary>
    private const double LongRoundSeconds = 0.2;

    /// <summary>The ceiling on rounds, when the interval never gets tight enough.</summary>
    private const int MaxRounds = 151;

    /// <summary>Rounds stop when half the interval width is within this fraction of the median.</summary>
    private const double Precision = 0.05;

    /// <summary>Wall clock one file may spend on rounds before it stops asking for more.</summary>
    /// <remarks>
    /// Fifty files at 54 s total means about a second each today. Two seconds is the most a file may
    /// take to reach its precision; `--quick` cuts it, and the encodings that need it are the cheap
    /// ones whose rounds are sub-millisecond anyway.
    /// </remarks>
    private static double Budget => Axis == Workload.Write ? 30.0 : (Quick ? 0.4 : 2.0);

    /// <summary>
    /// A round times at least this long, by repeating the scan when one is shorter.
    /// </summary>
    /// <remarks>
    /// Twenty files of the fifty scan in under 200 us at a million rows, and for half of those the
    /// ~40 us open is most of the measurement -- the 1M axis was built to escape the fixed cost and
    /// falls back into it from the other end on the cheap encodings. k scans
    /// per timed round is the same work with the timer's jitter divided by k.
    /// </remarks>
    private const double MinRoundMicroseconds = 2_000;

    /// <summary>Set by <c>--quick</c>: shorter warm-up and budget, for a direction rather than a gate.</summary>
    internal static bool Quick { get; set; }

    /// <summary>
    /// The margin over the reference ratio, the same +15% RatioCheck uses and for the same reason:
    /// the ratio is largely but not entirely deterministic, and a tighter margin gates noise.
    /// </summary>
    private const double Margin = 1.15;

    /// <summary>
    /// Files the REFERENCE cannot write, with the reason it gives.
    /// </summary>
    /// <remarks>
    /// A declared capability gap, not a swallowed exception, and the distinction is the whole
    /// point: a name in this list is skipped with its reason printed, and any other failure still
    /// aborts the axis loudly. Wrapping the measurement in a catch would hide the next one.
    /// <para>
    /// The reference's writer is given each split decoded, as ours is. A variant column's decoded
